<?php

use App\Http\Controllers\EventManagement\Workspace\MatchmakingController;
use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Matchmaking Workspace
|--------------------------------------------------------------------------
*/
Route::middleware([
          'auth',
          'event.access',
     ])
     ->prefix('matchmaking')
     ->name('matchmaking.')
     ->controller(MatchmakingController::class)
     ->group(function () {

          /*
          |--------------------------------------------------------------------------
          | View
          |--------------------------------------------------------------------------
          */
          Route::middleware(
               'permission:matchmaking.view'
          )->group(function () {

               /*
               |--------------------------------------------------------------------------
               | Index
               |--------------------------------------------------------------------------
               */
               Route::get(
                    '/',
                    'index'
               )->name('index');

               /*
               |--------------------------------------------------------------------------
               | Datatable
               |--------------------------------------------------------------------------
               */
               Route::post(
                    '/datatable',
                    'datatable'
               )->name('datatable');
          });

          /*
          |--------------------------------------------------------------------------
          | Create
          |--------------------------------------------------------------------------
          */
          Route::middleware(
               'permission:matchmaking.create'
          )->group(function () {

               /*
               |--------------------------------------------------------------------------
               | Create Meeting Request
               |--------------------------------------------------------------------------
               */
               Route::get(
                    '/create',
                    'create'
               )->name('create');

               /*
               |--------------------------------------------------------------------------
               | Store Meeting Request
               |--------------------------------------------------------------------------
               */
               Route::post(
                    '/',
                    'store'
               )->name('store');
          });
     });